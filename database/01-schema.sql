IF DB_ID(N'DormManagement') IS NULL CREATE DATABASE DormManagement;
GO
USE DormManagement;
GO

DROP TABLE IF EXISTS VIOLATION, ANNOUNCEMENT, INVOICE, CONTRACT, DOM_STAFF, STAFF, STUDENT, BED, ROOM, ROOMTYPE, DOM;
GO

CREATE TABLE DOM (
    DomID VARCHAR(10) NOT NULL CONSTRAINT PK_DOM PRIMARY KEY,
    DomName NVARCHAR(100) NOT NULL CONSTRAINT UQ_DOM_DomName UNIQUE
);

CREATE TABLE ROOMTYPE (
    TypeID INT NOT NULL CONSTRAINT PK_ROOMTYPE PRIMARY KEY,
    TypeNumber INT NOT NULL CONSTRAINT CK_ROOMTYPE_TypeNumber CHECK (TypeNumber > 0),
    RoomFee DECIMAL(10,2) NOT NULL CONSTRAINT CK_ROOMTYPE_RoomFee CHECK (RoomFee >= 0)
);

CREATE TABLE ROOM (
    RoomID VARCHAR(10) NOT NULL CONSTRAINT PK_ROOM PRIMARY KEY,
    DomID VARCHAR(10) NOT NULL CONSTRAINT FK_ROOM_DOM REFERENCES DOM(DomID),
    TypeID INT NOT NULL CONSTRAINT FK_ROOM_ROOMTYPE REFERENCES ROOMTYPE(TypeID),
    CurrentOccupancy INT NOT NULL CONSTRAINT DF_ROOM_Occupancy DEFAULT 0,
    RoomGender VARCHAR(10) NOT NULL CONSTRAINT CK_ROOM_Gender CHECK (RoomGender IN ('Male', 'Female')),
    CONSTRAINT CK_ROOM_Occupancy CHECK (CurrentOccupancy >= 0)
);

CREATE TABLE BED (
    BedID VARCHAR(10) NOT NULL CONSTRAINT PK_BED PRIMARY KEY,
    RoomID VARCHAR(10) NOT NULL CONSTRAINT FK_BED_ROOM REFERENCES ROOM(RoomID),
    BedStatus VARCHAR(20) NOT NULL CONSTRAINT DF_BED_Status DEFAULT 'Available',
    CONSTRAINT CK_BED_Status CHECK (BedStatus IN ('Available', 'Occupied'))
);

CREATE TABLE STUDENT (
    StudentID NVARCHAR(10) NOT NULL CONSTRAINT PK_STUDENT PRIMARY KEY,
    StudentName NVARCHAR(50) NOT NULL,
    DateBirth DATE NOT NULL,
    PhoneNumber VARCHAR(13) NOT NULL CONSTRAINT UQ_STUDENT_Phone UNIQUE,
    Email VARCHAR(100) NOT NULL CONSTRAINT UQ_STUDENT_Email UNIQUE,
    Location NVARCHAR(100) NULL,
    Gender VARCHAR(10) NOT NULL CONSTRAINT CK_STUDENT_Gender CHECK (Gender IN ('Male', 'Female'))
);

CREATE TABLE STAFF (
    StaffID NVARCHAR(10) NOT NULL CONSTRAINT PK_STAFF PRIMARY KEY,
    StaffName NVARCHAR(50) NOT NULL,
    PhoneNumber VARCHAR(20) NOT NULL CONSTRAINT UQ_STAFF_Phone UNIQUE,
    Role VARCHAR(20) NOT NULL
);

CREATE TABLE DOM_STAFF (
    DomID VARCHAR(10) NOT NULL CONSTRAINT FK_DOM_STAFF_DOM REFERENCES DOM(DomID),
    StaffID NVARCHAR(10) NOT NULL CONSTRAINT FK_DOM_STAFF_STAFF REFERENCES STAFF(StaffID),
    CONSTRAINT PK_DOM_STAFF PRIMARY KEY (DomID, StaffID)
);

CREATE TABLE CONTRACT (
    ContractID VARCHAR(10) NOT NULL CONSTRAINT PK_CONTRACT PRIMARY KEY,
    BedID VARCHAR(10) NOT NULL CONSTRAINT FK_CONTRACT_BED REFERENCES BED(BedID),
    StudentID NVARCHAR(10) NOT NULL CONSTRAINT FK_CONTRACT_STUDENT REFERENCES STUDENT(StudentID),
    Semester VARCHAR(20) NOT NULL,
    StartDate DATE NOT NULL,
    EndDate DATE NOT NULL,
    Status VARCHAR(20) NOT NULL CONSTRAINT CK_CONTRACT_Status CHECK (Status IN ('Active', 'Expired')),
    CONSTRAINT CK_CONTRACT_Dates CHECK (EndDate >= StartDate)
);

CREATE TABLE INVOICE (
    InvoiceID VARCHAR(10) NOT NULL CONSTRAINT PK_INVOICE PRIMARY KEY,
    RoomID VARCHAR(10) NOT NULL CONSTRAINT FK_INVOICE_ROOM REFERENCES ROOM(RoomID),
    BillingMonth DATE NOT NULL,
    ElectricFee DECIMAL(10,2) NOT NULL CONSTRAINT DF_INVOICE_Electric DEFAULT 0,
    WaterFee DECIMAL(10,2) NOT NULL CONSTRAINT DF_INVOICE_Water DEFAULT 0,
    InternetFee DECIMAL(10,2) NOT NULL CONSTRAINT DF_INVOICE_Internet DEFAULT 0,
    TotalPrice AS (ElectricFee + WaterFee + InternetFee) PERSISTED,
    Status VARCHAR(20) NOT NULL CONSTRAINT CK_INVOICE_Status CHECK (Status IN ('Paid', 'Unpaid')),
    CONSTRAINT UQ_INVOICE_Room_Month UNIQUE (RoomID, BillingMonth),
    CONSTRAINT CK_INVOICE_Fees CHECK (ElectricFee >= 0 AND WaterFee >= 0 AND InternetFee >= 0),
    CONSTRAINT CK_INVOICE_BillingMonth CHECK (DAY(BillingMonth) = 1)
);

CREATE TABLE ANNOUNCEMENT (
    AnnouncementID VARCHAR(10) NOT NULL CONSTRAINT PK_ANNOUNCEMENT PRIMARY KEY,
    StaffID NVARCHAR(10) NOT NULL CONSTRAINT FK_ANNOUNCEMENT_STAFF REFERENCES STAFF(StaffID),
    DomID VARCHAR(10) NULL CONSTRAINT FK_ANNOUNCEMENT_DOM REFERENCES DOM(DomID),
    RoomID VARCHAR(10) NULL CONSTRAINT FK_ANNOUNCEMENT_ROOM REFERENCES ROOM(RoomID),
    Title NVARCHAR(100) NOT NULL,
    Content NVARCHAR(MAX) NOT NULL,
    AnnouncementDate DATETIME NOT NULL CONSTRAINT DF_ANNOUNCEMENT_Date DEFAULT GETDATE(),
    CONSTRAINT CK_ANNOUNCEMENT_Target CHECK ((DomID IS NOT NULL AND RoomID IS NULL) OR (DomID IS NULL AND RoomID IS NOT NULL))
);

CREATE TABLE VIOLATION (
    ViolationID VARCHAR(10) NOT NULL CONSTRAINT PK_VIOLATION PRIMARY KEY,
    StaffID NVARCHAR(10) NOT NULL CONSTRAINT FK_VIOLATION_STAFF REFERENCES STAFF(StaffID),
    StudentID NVARCHAR(10) NULL CONSTRAINT FK_VIOLATION_STUDENT REFERENCES STUDENT(StudentID),
    RoomID VARCHAR(10) NULL CONSTRAINT FK_VIOLATION_ROOM REFERENCES ROOM(RoomID),
    ViolationName NVARCHAR(200) NOT NULL,
    ViolationDate DATE NOT NULL,
    CONSTRAINT CK_VIOLATION_Target CHECK ((StudentID IS NOT NULL AND RoomID IS NULL) OR (StudentID IS NULL AND RoomID IS NOT NULL))
);
GO

CREATE INDEX IX_ROOM_DOM ON ROOM(DomID);
CREATE INDEX IX_BED_ROOM_STATUS ON BED(RoomID, BedStatus);
CREATE INDEX IX_CONTRACT_STUDENT_STATUS ON CONTRACT(StudentID, Status);
CREATE UNIQUE INDEX UX_CONTRACT_ACTIVE_STUDENT ON CONTRACT(StudentID) WHERE Status = 'Active';
CREATE UNIQUE INDEX UX_CONTRACT_ACTIVE_BED ON CONTRACT(BedID) WHERE Status = 'Active';
GO

CREATE OR ALTER TRIGGER TRG_CONTRACT_SYNC ON CONTRACT
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (
        SELECT 1 FROM inserted i
        JOIN STUDENT s ON s.StudentID = i.StudentID
        JOIN BED b ON b.BedID = i.BedID
        JOIN ROOM r ON r.RoomID = b.RoomID
        WHERE i.Status = 'Active' AND s.Gender <> r.RoomGender
    )
    BEGIN
        ROLLBACK TRANSACTION;
        THROW 51000, N'Giới tính sinh viên không phù hợp với phòng.', 1;
    END;

    UPDATE b SET BedStatus = CASE WHEN EXISTS (
        SELECT 1 FROM CONTRACT c WHERE c.BedID = b.BedID AND c.Status = 'Active'
    ) THEN 'Occupied' ELSE 'Available' END
    FROM BED b
    WHERE b.BedID IN (SELECT BedID FROM inserted UNION SELECT BedID FROM deleted);

    UPDATE r SET CurrentOccupancy = (
        SELECT COUNT(*) FROM BED b JOIN CONTRACT c ON c.BedID = b.BedID
        WHERE b.RoomID = r.RoomID AND c.Status = 'Active'
    )
    FROM ROOM r
    WHERE r.RoomID IN (
        SELECT b.RoomID FROM BED b
        WHERE b.BedID IN (SELECT BedID FROM inserted UNION SELECT BedID FROM deleted)
    );
END;
GO

